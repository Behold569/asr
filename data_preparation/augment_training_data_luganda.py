"""
Data Augmentation for Nonstandard Speech ASR Fine-tuning

Script for audio data augmentation used in
Whisper fine-tuning for Luganda nonstandard speech.

Three augmentation techniques are applied stochastically:
1. Gaussian noise addition
2. Gain perturbation (volume change)
3. Speed perturbation (via resampling)

Each augmentation is applied independently with 50% probability.

Usage:
    from augment_audio import augment_audio
    augmented = augment_audio(audio_array, sampling_rate)
"""

import numpy as np
import torch
import torchaudio


def augment_audio(audio_array, sampling_rate):
    audio = audio_array.astype(np.float32)

    if np.random.rand() < 0.5:
        noise_level = np.random.uniform(0.001, 0.015)
        audio = audio + noise_level * np.random.randn(len(audio))

    if np.random.rand() < 0.5:
        gain = np.random.uniform(0.7, 1.3)
        audio = audio * gain

    if np.random.rand() < 0.5:
        speed_factor = np.random.uniform(0.9, 1.1)
        audio_tensor = torch.tensor(audio).unsqueeze(0)
        resampled = torchaudio.functional.resample(
            audio_tensor,
            orig_freq=int(sampling_rate * speed_factor),
            new_freq=sampling_rate
        )
        audio = resampled.squeeze(0).numpy()

    return np.clip(audio, -1.0, 1.0)